test('Settings and Profile fit phones, split/tablet views, desktop, and short keyboard windows', async ({ page }) => {
  test.setTimeout(60_000)
  for (const [width, height] of [[320, 812], [375, 812], [600, 900], [760, 1024], [834, 1194], [1194, 834], [1440, 1000], [375, 420], [812, 320]]) {
    await page.setViewportSize({ width, height })
    await page.goto('/settings')
    await expect(darkMode(page)).toBeEnabled()
    await page.evaluate(() => document.fonts.ready)
    await settle(page)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    const targets = await page.locator('.settings-page a, .settings-page button, .settings-page input, .profile-trigger').evaluateAll((elements) => elements.map((element) => {
      const rect = element.getBoundingClientRect()
      return { width: rect.width, height: rect.height }
    }))
    for (const target of targets) { expect(target.width).toBeGreaterThanOrEqual(44); expect(target.height).toBeGreaterThanOrEqual(44) }
    await openProfile(page)
    let panel = await box(page.locator('.profile-panel'))
    expect(panel.x).toBeGreaterThanOrEqual(0)
    expect(panel.right).toBeLessThanOrEqual(width)
    expect(panel.y).toBeGreaterThanOrEqual(0)
    expect(panel.bottom).toBeLessThan((await box(bottom(page))).y)
    for (const link of await profile(page).getByRole('link').all()) {
      await link.focus()
      await settle(page)
      const target = await box(link)
      panel = await box(page.locator('.profile-panel'))
      expect(target.y).toBeGreaterThanOrEqual(panel.y)
      expect(target.bottom).toBeLessThanOrEqual(panel.bottom)
      expect(target.width).toBeGreaterThanOrEqual(44)
      expect(target.height).toBeGreaterThanOrEqual(44)
    }
    await page.keyboard.press('Escape')
    const source = page.getByRole('link', { name: 'Source code', exact: false })
    await source.focus()
    await settle(page)
    const last = await box(source)
    expect(last.y).toBeGreaterThanOrEqual((await box(page.locator('.topbar'))).bottom)
    expect(last.bottom).toBeLessThan((await box(bottom(page))).y)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    if (height <= 420) {
      await index(page).getByRole('link', { name: 'Privacy & storage', exact: true }).click()
      await expect(page.locator('#privacy')).toBeFocused()
      expect((await box(page.locator('#privacy h2'))).y).toBeGreaterThanOrEqual((await box(page.locator('.topbar'))).bottom)
    }
  }
  await page.setViewportSize({ width: 375, height: 812 })
  await page.evaluate(() => {
    const root = document.documentElement
    root.style.setProperty('--safe-area-bottom', '34px')
    root.style.setProperty('--safe-area-left', '24px')
    root.style.setProperty('--safe-area-right', '24px')
  })
  await openProfile(page)
  const panel = await box(page.locator('.profile-panel'))
  expect(panel.x).toBeGreaterThanOrEqual(24)
  expect(panel.right).toBeLessThanOrEqual(375 - 24)
  await page.keyboard.press('Escape')
  await page.evaluate(() => window.scrollTo({ top: document.body.scrollHeight, behavior: 'instant' }))
  await settle(page)
  expect((await box(page.getByRole('contentinfo'))).bottom).toBeLessThan((await box(bottom(page))).y)
})

