test('Settings supports direct visits, refresh, section URLs, and Back/Forward scroll restoration', async ({ page }) => {
  await page.goto('/settings')
  await expect(page).toHaveTitle('Settings · Kanso Pro')
  await expect(darkMode(page)).toBeEnabled()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Skip to page content', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('main')).toBeFocused()
  await index(page).getByRole('link', { name: 'Privacy & storage', exact: true }).click()
  await expect(page).toHaveURL('/settings#privacy')
  await expect(page.locator('#privacy')).toBeFocused()
  expect((await box(page.locator('#privacy'))).y).toBeGreaterThanOrEqual((await box(page.locator('.topbar'))).bottom)
  await page.evaluate(() => window.scrollBy({ top: 125, behavior: 'instant' }))
  await settle(page)
  const position = await page.evaluate(() => window.scrollY)
  await bottom(page).getByRole('link', { name: 'Calendar', exact: true }).click()
  await expect(page).toHaveURL('/calendar')
  await page.goBack()
  await expect(page.locator('#privacy')).toBeFocused()
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeCloseTo(position, 0)
  await page.goForward()
  await expect(page).toHaveURL('/calendar')
  await page.goto('/settings#appearance')
  await expect(page.locator('#appearance')).toBeFocused()
  await expect(index(page).getByRole('link', { name: 'Appearance', exact: true })).toHaveAttribute('aria-current', 'location')
  await page.reload()
  await expect(page.locator('#appearance')).toBeFocused()
  expect((await box(page.locator('#appearance'))).y).toBeGreaterThanOrEqual((await box(page.locator('.topbar'))).bottom)
  // Hash history also restores a previously visited section/top-of-page.
  await index(page).getByRole('link', { name: 'About & help', exact: true }).click()
  await expect(page.locator('#about')).toBeFocused()
  await page.goBack()
  await expect(page.locator('#appearance')).toBeFocused()
  await page.goForward()
  await expect(page.locator('#about')).toBeFocused()
  await page.goto('/settings/unknown')
  await expect(page).toHaveTitle('Page not found · Kanso Pro')
  await expect(page.getByRole('heading', { name: 'This page isn’t here.', exact: true })).toBeVisible()
})

