    const user = { uid: 'test-only-ada', displayName: 'Ada Reyes', email: 'ada@example.test', emailVerified: false, providers: ['password'] }
    window.__signOutCalls = 0
    window.__observerCalls = 0
    export function observeAccount(callback) { window.__observerCalls++; queueMicrotask(() => callback(user)); return () => {} }
    export function currentAccount() { return user }
    export async function signOutAccount() { window.__signOutCalls++; await new Promise(resolve => { window.__releaseSignOut = resolve }); throw Object.assign(new Error('Test-only failure'), { code: 'auth/network-request-failed' }) }
