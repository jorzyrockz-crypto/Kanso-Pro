test('Spaces keep local team work separate and let owners configure shared workspace identity and members', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/')

  const switcher = page.getByRole('button', { name: /Switch workspace, current space: Personal Space/ })
  await expect(switcher).toBeVisible()
  await switcher.click()
  await expect(page.getByRole('dialog', { name: 'Switch workspace' })).toContainText('Personal Space')
  await page.getByRole('option', { name: /Curriculum Planning/ }).click()
  await expect(page.getByRole('button', { name: /Switch workspace, current space: Curriculum Planning/ })).toBeVisible()
  const memberProfile = page.getByRole('button', { name: 'Configure Curriculum Planning workspace settings', exact: true })
  await expect(memberProfile).toBeVisible()
  await expect(page.getByRole('button', { name: 'Manage', exact: true })).toHaveCount(0)
  await expect(page.getByText('Local Space', { exact: true })).toBeVisible()
  await memberProfile.click()
  const settings = page.getByRole('dialog', { name: 'Configure Curriculum Planning' })
  await expect(settings).toBeVisible()
  const appearance = settings.locator('.workspace-appearance-disclosure')
  await expect(appearance).not.toHaveAttribute('open', '')
  await appearance.locator('summary').click()
  await expect(appearance).toHaveAttribute('open', '')
  await settings.getByLabel('Workspace title', { exact: true }).fill('Curriculum Studio')
  await settings.getByRole('button', { name: 'Forest workspace color', exact: true }).click()
  await settings.getByRole('button', { name: 'Book workspace icon', exact: true }).click()
  await settings.getByLabel('Name', { exact: true }).fill('Ana Reyes')
  await settings.getByLabel('Email', { exact: true }).fill('ana.reyes@example.test')
  await settings.getByLabel('New member role', { exact: true }).selectOption('viewer')
  await settings.getByRole('button', { name: 'Add member', exact: true }).click()
  await expect(settings.getByRole('list', { name: 'Workspace members' })).toContainText('Ana Reyes')
  await settings.getByLabel('Role for Ana Reyes', { exact: true }).selectOption('editor')
  await settings.getByRole('button', { name: 'Remove Ana Reyes', exact: true }).click()
  await expect(settings.getByRole('list', { name: 'Workspace members' })).not.toContainText('Ana Reyes')
  await settings.getByRole('button', { name: 'Save workspace', exact: true }).click()
  await expect(settings).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Switch workspace, current space: Curriculum Studio/ })).toBeVisible()

  await page.goto('/new?type=event')
  await expect(page.getByLabel('Calendar or organization', { exact: false })).toHaveValue('Curriculum Studio')
  await expect(page.getByLabel('Organizer', { exact: false })).toHaveValue('You')

  await page.goto('/projects/proj-tos')
  await expect(page.getByRole('button', { name: 'All Team', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /My Work/ }).click()
  await expect(page.getByRole('button', { name: /My Work/ })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'All Team', exact: true }).click()
  await page.getByRole('button', { name: 'Edit milestone 2', exact: true }).click()
  await page.getByLabel('Milestone 2 assignee', { exact: true }).selectOption('J. Santos')
  await page.getByRole('button', { name: 'Save milestone', exact: true }).click()
  await page.getByRole('button', { name: /Notifications/ }).click()
  await expect(page.getByRole('dialog', { name: 'Notifications' })).toContainText('Assignment updated')
  await page.keyboard.press('Escape')
  const reaction = page.getByRole('button', { name: 'Add 👍 reaction', exact: true }).first()
  await reaction.click()
  await expect(page.getByRole('button', { name: /Remove 👍 reaction/ }).first()).toHaveAttribute('aria-pressed', 'true')

  await page.goto('/calendar?date=2026-11-15')
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('button', { name: 'Task', exact: true }).click()
  await page.getByPlaceholder('Task title').fill('Draft the family invitation')
  await page.getByRole('button', { name: /Add to Nov 15/ }).click()
  await expect(page.getByText('Draft the family invitation', { exact: true })).toBeVisible()

  await page.goto('/tasks/task-grades')
  await page.getByRole('button', { name: 'Add comment', exact: true }).first().click()
  await page.getByLabel('Add a comment', { exact: true }).fill('I can take the first pass this afternoon.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByText('I can take the first pass this afternoon.', { exact: true })).toBeVisible()

  await page.goto('/journal')
  await expect(page.getByText('Space Notes · this device', { exact: true })).toBeVisible()
  await expect(page.getByText(/Space Note/i).first()).toBeVisible()
})

test('new teammate activity arrives as an unopened envelope on the Journey Stream spine', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await page.getByRole('button', { name: /Switch workspace, current space: Personal Space/ }).click()
  await page.getByRole('option', { name: /Curriculum Planning/ }).click()
  await expect(page.getByRole('heading', { name: 'Journey Stream', exact: true })).toBeVisible()
  await page.waitForFunction(({ key, spaceId }) => {
    const stored = localStorage.getItem(key)
    if (!stored) return false
    try { return Boolean(JSON.parse(stored).spaces?.[spaceId]) } catch { return false }
  }, { key: SPINE_ACTIVITY_ENVELOPE_KEY, spaceId: 'space-curriculum-planning' })

  await page.evaluate(({ key }) => {
    const state = JSON.parse(localStorage.getItem(key)!)
    state.activity['space-curriculum-planning'] = [{
      id: 'activity-envelope', kind: 'assignment', title: 'Assignment updated', detail: 'J. Santos assigned “Review the parent letter” to you.', href: '/tasks/task-grades', createdAt: '2026-11-15T09:00:00.000Z', actor: 'J. Santos', target: 'You',
    }]
    const value = JSON.stringify(state)
    localStorage.setItem(key, value)
    window.dispatchEvent(new StorageEvent('storage', { key, newValue: value, storageArea: localStorage }))
  }, { key: SPACES_STORAGE_KEY })

  const envelope = page.getByRole('button', { name: '1 new teammate activity. Open activity tray.' })
  await expect(envelope).toBeVisible()
  await expect(envelope).toHaveCSS('animation-name', 'spine-envelope-arrive')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(envelope).toHaveCSS('animation-name', 'none')
  await envelope.click()
  const tray = page.getByRole('dialog', { name: '1 new update' })
  await expect(tray).toContainText('Assignment updated')
  await expect(tray).toContainText('Review the parent letter')
  await expect(envelope).toHaveCount(0)
  await tray.getByRole('button', { name: 'Close new activity tray' }).click()
  await expect(tray).toHaveCount(0)
  await expect(envelope).toHaveCount(0)
})

test('a shared Space keeps one replaceable Pinned Space Notice outside the Journey Stream', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/')
  await expect(page.getByText('Pinned Space Notice', { exact: true })).toHaveCount(0)

  await page.getByRole('button', { name: /Switch workspace, current space: Personal Space/ }).click()
  await page.getByRole('option', { name: /Curriculum Planning/ }).click()
  const noticeAction = page.getByRole('button', { name: 'Pinned notice', exact: true })
  await noticeAction.click()
  await page.getByPlaceholder('Share one concise notice…').fill('Please review the family-conference plan before lunch.')
  await page.getByRole('button', { name: 'Post', exact: true }).click()
  const notice = page.getByRole('region', { name: 'Pinned Space Notice', exact: true })
  await expect(notice).toContainText('Please review the family-conference plan before lunch.')
  await expect(notice).toContainText(/Pinned by You · Today at/)
  await expect(page.getByText('Space update', { exact: true })).toHaveCount(0)

  await page.getByRole('button', { name: 'Edit notice', exact: true }).click()
  await page.getByPlaceholder('Share one concise notice…').fill('Family-conference plan is confirmed for Friday.')
  await page.getByRole('button', { name: 'Replace', exact: true }).click()
  await expect(notice).toContainText('Family-conference plan is confirmed for Friday.')
  await expect(notice).not.toContainText('Please review the family-conference plan before lunch.')
  await page.getByRole('button', { name: 'Got it', exact: true }).click()
  await expect(notice).toContainText('1 acknowledged')
  await page.getByRole('button', { name: 'Minimize pinned Space notice', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Show', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Show', exact: true }).click()
  await expect(notice).toContainText('Family-conference plan is confirmed for Friday.')
  await page.setViewportSize({ width: 375, height: 812 })
  await expect(page.getByRole('button', { name: 'Edit notice', exact: true })).toBeVisible()
  await expect(page.getByRole('group', { name: 'Team workload scope', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)

  await page.getByRole('button', { name: /Switch workspace, current space: Curriculum Planning/ }).click()
  await page.getByRole('option', { name: /Personal Space/ }).click()
  await expect(page.getByRole('region', { name: 'Pinned Space Notice', exact: true })).toHaveCount(0)
})
