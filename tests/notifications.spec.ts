import { expect, test } from '@playwright/test'
import { createInitialState, STORAGE_KEY } from '../src/data'
import type { TaskCard } from '../src/types'
import { mockFirebase } from './helpers/firebase'

test.use({ timezoneId: 'Asia/Manila' })

const bell = (page: import('@playwright/test').Page) => page.getByRole('link', { name: /^Notifications(?:,|$)/ })
const openNewCard = async (page: import('@playwright/test').Page) => {
  await page.getByRole('button', { name: 'More', exact: true }).click()
  await page.getByRole('button', { name: 'New card', exact: true }).click()
}

test('no initial flood or permission prompt; due reminders group, badge, link and mark read', async ({ page, context }) => {
  await context.grantPermissions([])
  const firebase = await mockFirebase(context)
  const state = createInitialState()
  const source = state.cards.find((card): card is TaskCard => card.type === 'task')!
  state.cards = Array.from({ length: 11 }, (_, index): TaskCard => ({ ...source, id: `due-${index + 1}`, title: `Reminder task ${index + 1}`, date: '2026-11-14', reminder: '09:00', subtasks: [{ id: `step-${index}`, title: 'A small step', done: false }] }))
  await page.addInitScript(({ key, value }) => {
    localStorage.setItem(key, value)
    Object.defineProperty(window, 'Notification', { configurable: true, value: class { static permission = 'default'; static requestPermission() { document.documentElement.dataset.permissionAsked = 'yes'; return Promise.resolve('denied') } } })
    Object.defineProperty(navigator, 'setAppBadge', { configurable: true, value: async (count: number) => { document.documentElement.dataset.badge = String(count) } })
    Object.defineProperty(navigator, 'clearAppBadge', { configurable: true, value: async () => { document.documentElement.dataset.badge = '0' } })
  }, { key: STORAGE_KEY, value: JSON.stringify(state) })
  // Explicit clock with timezone below: 08:59 on the planner’s device, not UTC midnight.
  await page.clock.install({ time: new Date('2026-11-14T00:59:00Z') })
  await page.goto('/notifications')
  await expect(page.getByRole('heading', { name: 'A little breathing room.' })).toBeVisible()
  await expect(bell(page)).toHaveAttribute('aria-label', 'Notifications')
  await expect(page.locator('html')).not.toHaveAttribute('data-permission-asked')
  await openNewCard(page)
  await page.locator('#card-title').fill('Unfinished reminder-time draft')
  await page.clock.fastForward(60_001)
  await expect(page.locator('.toast')).toContainText('11 new planner notifications')
  page.once('dialog', dialog => dialog.dismiss())
  await page.locator('.toast-action').click()
  await expect(page.locator('#card-title')).toHaveValue('Unfinished reminder-time draft')
  page.once('dialog', dialog => dialog.accept())
  await page.locator('.toast-action').click()
  await expect(page).toHaveURL('/notifications')
  await expect(page.locator('.notification-item')).toHaveCount(11)
  await expect(bell(page)).toHaveAttribute('aria-label', 'Notifications, 11 unread')
  await expect(page.locator('.notification-count')).toHaveText('9+')
  await expect(page.locator('html')).toHaveAttribute('data-badge', '11')
  await expect(page.locator('.toast')).toContainText('11 new planner notifications')
  await page.getByRole('link', { name: /Task reminder · Reminder task 1\b/ }).click()
  await expect(page).toHaveURL('/tasks/due-1')
  await expect(bell(page)).toHaveAttribute('aria-label', 'Notifications, 10 unread')
  await bell(page).click()
  await page.getByRole('button', { name: 'Mark all read', exact: true }).click()
  await expect(bell(page)).toHaveAttribute('aria-label', 'Notifications')
  await expect(page.locator('html')).toHaveAttribute('data-badge', '0')
  await page.clock.fastForward(60_001)
  await expect(page.locator('.notification-item')).toHaveCount(11)
  await expect(page.locator('html')).not.toHaveAttribute('data-permission-asked')
  expect(firebase.requests).toEqual([])
  expect(firebase.unexpectedRequests).toEqual([])
})

test.describe('touch notification preferences', () => {
  test.use({ hasTouch: true })
  test('phone-size bell and settings synchronize without changing cards or adding a planning tab', async ({ page, context }) => {
    await mockFirebase(context)
    await page.setViewportSize({ width: 320, height: 740 })
    await page.goto('/notifications')
    await expect(page.getByRole('heading', { name: 'Notifications', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
    await page.getByRole('button', { name: 'More', exact: true }).click()
    await expect(page.getByRole('button', { name: 'New card', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    const bounds = await bell(page).boundingBox()
    expect(bounds!.width).toBeGreaterThanOrEqual(44)
    expect(bounds!.height).toBeGreaterThanOrEqual(44)
    await expect(page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link')).toHaveCount(5)
    const saved = await page.evaluate(key => localStorage.getItem(key), STORAGE_KEY)
    const other = await context.newPage()
    await other.goto('/notifications')
    await page.getByRole('checkbox', { name: /^Events/ }).uncheck()
    await expect(other.getByRole('checkbox', { name: /^Events/ })).not.toBeChecked()
    await page.getByLabel('From', { exact: true }).fill('20:00')
    await expect(other.getByLabel('From', { exact: true })).toHaveValue('20:00')
    await expect(page.getByLabel('Until', { exact: true })).toHaveValue('06:00')
    await page.getByRole('checkbox', { name: /^Phone notifications/ }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Phone notifications need' })).toBeVisible()
    await expect(page.getByRole('checkbox', { name: /^Phone notifications/ })).not.toBeChecked()
    expect(await page.evaluate(key => localStorage.getItem(key), STORAGE_KEY)).toBe(saved)
    await page.getByRole('link', { name: 'Kanso Pro home', exact: true }).click()
    await page.goBack()
    await expect(page).toHaveURL('/notifications')
    await expect(page.getByRole('heading', { name: 'Notifications', exact: true })).toBeVisible()
    await other.close()
  })
})
