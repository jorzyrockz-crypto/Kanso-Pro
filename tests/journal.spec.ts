import { expect, test } from '@playwright/test'

const navigation = (page: import('@playwright/test').Page) => page.getByRole('navigation', { name: 'Main navigation' })

test('Journal offers the responsive note studio with local voice and private Firestore image paths', async ({ page }) => {
  await page.goto('/journal')
  const recentHeading = page.getByRole('heading', { name: 'Recent entries', exact: true })
  const entryHeading = page.locator('.journal-recent .panel-heading')
  const entrySearch = page.locator('.journal-hub .journal-recent > .journal-search')
  await expect(recentHeading).toBeVisible()
  await expect(entrySearch).toBeVisible()
  const [headingBox, searchBox] = await Promise.all([entryHeading.boundingBox(), entrySearch.boundingBox()])
  expect(Math.abs((headingBox!.y + headingBox!.height / 2) - (searchBox!.y + searchBox!.height / 2))).toBeLessThanOrEqual(1)
  await navigation(page).getByRole('button', { name: 'New note', exact: true }).click()
  await expect(page).toHaveURL('/journal?create=menu')
  await expect(page.getByRole('heading', { name: 'Start a journal entry', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /Text entry/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /Voice entry/ })).toBeVisible()

  await page.getByRole('button', { name: /Text entry/ }).click()
  await expect(page).toHaveURL(/\/journal\/note-/)
  await page.getByLabel('Note title', { exact: true }).fill('A local journal note')
  const reflection = page.getByLabel('Your reflection', { exact: true })
  await reflection.fill('This note stays on this device.')
  await page.getByRole('button', { name: 'Checklist', exact: true }).click()
  await expect(reflection.locator('input[type="checkbox"]')).toHaveCount(1)
  await page.getByLabel('Tags, separated by commas', { exact: true }).fill('private, journal')
  await page.getByLabel('Note category', { exact: true }).selectOption('Personal')
  await page.locator('.studio-back-to-notes').click()
  await expect(page.getByRole('link', { name: 'Open Text journal entry: A local journal note', exact: true })).toBeVisible()

  await navigation(page).getByRole('button', { name: 'New note', exact: true }).click()
  await page.getByRole('button', { name: /Voice entry/ }).click()
  await expect(page.getByRole('button', { name: 'Start recording', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Checklist', exact: true })).toBeVisible()

  await page.goto('/journal?create=menu')
  const imageNote = page.getByRole('button', { name: /Photo entry/ })
  await expect(imageNote).toBeDisabled()
  await expect(imageNote).toContainText('Sign in with Google to store images privately.')
})

test('Journal uses a three-column library board and a single-column studio rail on larger screens', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/journal')
  const boardEntries = page.locator('.journal-note-list:not(.is-compact)')
  await expect(boardEntries).toBeVisible()
  expect(await boardEntries.evaluate((element) => getComputedStyle(element).gridTemplateColumns.trim().split(/\s+/).length)).toBe(3)

  await page.goto('/journal/note-lesson')
  const rail = page.getByRole('complementary', { name: 'Journal entries', exact: true })
  await expect(rail).toBeVisible()
  const railEntries = rail.locator('.journal-note-summary')
  const [firstRailEntry, secondRailEntry] = await Promise.all([railEntries.nth(0).boundingBox(), railEntries.nth(1).boundingBox()])
  expect(Math.abs(firstRailEntry!.x - secondRailEntry!.x)).toBeLessThanOrEqual(1)
  await expect(page.getByRole('toolbar', { name: 'Rich text formatting', exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Your reflection', exact: true })).toBeVisible()

  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('complementary', { name: 'Journal entries', exact: true })).toBeHidden()
  await expect(page.locator('.studio-back-to-notes')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Add photo', exact: true })).toBeDisabled()
})
